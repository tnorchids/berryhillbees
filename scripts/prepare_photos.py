"""Regenerate responsive photos from the untouched sibling-site sources.

Requires Python and Pillow. Run from any directory; paths are relative to this file.
"""

import json
from pathlib import Path
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
SITES = ROOT.parent
OUTPUT = ROOT / 'src/assets/photos'
OUTPUT.mkdir(parents=True, exist_ok=True)

# name: (source, largest useful width, optional source-pixel crop)
SOURCES = {
    'homeHives': ('bhb-beta/src/assets/images/home/originals/bhbhives.JPG', 2400, None),
    'bigHives': ('bhb-beta/src/assets/images/bees/originals/big-ole-hives.JPG', 2400, (0, 950, 4928, 3029)),
    'italians': ('bhb-beta/src/assets/images/bees/originals/italians.JPG', 1200, None),
    'activity': ('bhb-beta/src/assets/images/bees/originals/bee-activity.JPG', 1200, (0, 0, 4352, 3264)),
    'watching': ('bhb-legacy/images/bees/granolas-ls.png', 1024, None),
    'firstHives': ('bhb-legacy/images/about/bhb-starting-out.png', 1024, None),
    'dadsHives': ('bhb-legacy/images/about/dad-bees.png', 640, None),
    'flipTopHoney': ('bhb-beta/src/assets/images/products/originals/flip-top-honey-01.JPG', 1200, None),
    'muthHoney': ('bhb-beta/src/assets/images/products/originals/muth-honey-01.JPG', 1200, None),
    'honeyCream': ('bhb-beta/src/assets/images/products/originals/honey-cream-01.png', 1024, None),
    'lipBalm': ('bhb-beta/src/assets/images/products/originals/lipbalm-01.png', 1011, None)
}

imports = ['// Generated by scripts/prepare_photos.py; do not edit by hand.']
entries = []
report = []
for name, (source, maximum, crop) in SOURCES.items():
    with Image.open(SITES / source) as original:
        photo = ImageOps.exif_transpose(original).convert('RGB')
    if crop:
        photo = photo.crop(crop)
    maximum = min(maximum, photo.width)
    widths = sorted({w for w in (400, 640, 960, 1200, 1600, 2400) if w < maximum} | {maximum})
    variants = []
    for width in widths:
        height = round(photo.height * width / photo.width)
        resized = photo.resize((width, height), Image.Resampling.LANCZOS)
        filename = f'{name}-{width}.webp'
        resized.save(OUTPUT / filename, 'WEBP', quality=94, method=6)
        variable = f'{name}{width}'
        imports.append(f"import {variable} from '../assets/photos/{filename}';")
        variants.append(f'`${{{variable}}} {width}w`')
    entries.append(f"  {name}: {{ src: {name}{maximum}, width: {maximum}, height: {round(photo.height * maximum / photo.width)}, srcSet: [{', '.join(variants)}].join(', ') }}")
    report.append({'name': name, 'source': source, 'widths': widths, 'largestBytes': (OUTPUT / f'{name}-{maximum}.webp').stat().st_size})

(ROOT / 'src/data/photos.js').write_text('\n'.join(imports) + '\n\nexport const photos = {\n' + ',\n'.join(entries) + '\n};\n', encoding='utf-8')
(OUTPUT / 'sources.json').write_text(json.dumps(report, indent=2) + '\n', encoding='utf-8')
for row in report:
    print(f"{row['name']}: {row['widths']}; largest {row['largestBytes'] // 1024} KB")
